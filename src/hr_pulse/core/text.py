"""Работа с текстом: приведение названий колонок из выгрузок 1С к единому виду."""

import re


def normalize_header(raw: str) -> str:
    """Приводит название колонки к единому виду, чтобы его можно было сравнивать.
    Пример: "Дата приёма" → "дата приема", "Таб. Номер" → "таб номер".
    """
    # 1. Неразрывный пробел (частый гость в выгрузках 1С) → обычный пробел
    text = raw.replace("\xa0", " ")
    # 2. «ё» → «е»: в одной выгрузке «приёма», в другой «приема»
    text = text.replace("ё", "е").replace("Ё", "Е")
    # 3. Регистр не важен
    text = text.lower()
    # 4. Знаки препинания (точки, скобки, дефисы) → пробел
    text = re.sub(r"[^\w\s]", " ", text)
    # 5. Несколько пробелов подряд → один, края обрезаем
    text = re.sub(r"\s+", " ", text)
    return text.strip()
